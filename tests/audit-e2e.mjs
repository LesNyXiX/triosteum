import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFileSync } from 'node:fs';
const html = readFileSync(new URL('../docs/index.html', import.meta.url));
const srv = createServer((q,r)=>{r.writeHead(200,{'content-type':'text/html; charset=utf-8'});r.end(html);});
await new Promise(ok=>srv.listen(0,'127.0.0.1',ok));
const browser = await chromium.launch(); let failed=0;
const check=(ok,name)=>{console.log((ok?'  ✓ ':'  ✗ ')+name);if(!ok)failed++;};
try {
  const ctx=await browser.newContext({viewport:{width:1400,height:900}});
  await ctx.addInitScript(()=>{
    if(window.top!==window||localStorage.getItem('__auditSeed'))return;
    localStorage.setItem('__auditSeed','1');
    const graph={nodes:[{id:'a',name:'База',lang:'cpp',kind:'block',x:100,y:180,codes:{cpp:'int run(){ return 1; }'}}],edges:[],notes:[],seq:3,cam:{x:0,y:0,k:1}};
    localStorage.setItem('triosteum.projects',JSON.stringify({cur:'p1',list:[{id:'p1',name:'Аудит',env:'code',t:Date.now()},{id:'p2',name:'Другое',env:'code',t:Date.now()}]}));
    localStorage.setItem('triosteum.proj.p1',JSON.stringify(graph));localStorage.setItem('triosteum.proj.p2',JSON.stringify({...graph,nodes:[]}));
    localStorage.setItem('triosteum.profile','{"name":"Тестовый автор","org":"Тест"}');localStorage.setItem('triosteum.tour','{"done":true}');
  });
  const page=await ctx.newPage(), errors=[];page.on('pageerror',e=>{if(!/sandboxed/.test(e.message))errors.push(e.message);});
  await page.goto('http://127.0.0.1:'+srv.address().port);await page.locator('.node').first().waitFor();
  const cmd=async(text)=>{await page.keyboard.press('Control+k');await page.locator('#cmdQ').fill(text);await page.keyboard.press('Enter');};
  const records=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('triosteum.audit:p1')||'[]'));
  await cmd('Новый блок C++');await page.waitForTimeout(550);
  const added=page.locator('.node').last();await added.click({button:'right'});await page.locator('#popName').fill('Переименованный');await page.waitForTimeout(450);
  await page.locator('#pop').getByRole('button',{name:'Удалить',exact:true}).click();await page.waitForTimeout(450);
  await page.locator('#topRun').click();await page.waitForFunction(()=>!document.querySelector('#runGo').disabled);await page.locator('#runClose').click();
  const list=await records();
  check(list.length===4 && ['node_add','node_name','node_del','run'].every(t=>list.some(r=>r.type===t)),'добавление, переименование, удаление и запуск — четыре записи');
  check(list.every(r=>r.who==='Тестовый автор'),'имя автора берётся из профиля');
  check(list.some(r=>r.type==='node_name' && /→ Переименованный/.test(r.detail)),'переименование содержит было → стало');
  await cmd('Журнал действий');
  check(await page.locator('.aud-row').count()===4,'журнал показывает четыре записи');
  await page.getByRole('combobox',{name:'Тип действия'}).selectOption('run');
  check(await page.locator('.aud-row').count()===1,'фильтр по типу');
  await page.getByRole('combobox',{name:'Тип действия'}).selectOption('');
  await page.getByRole('searchbox',{name:'Поиск в журнале'}).fill('Переименованный');
  check(await page.locator('.aud-row').count()===2,'поиск по имени объекта');
  await page.getByRole('searchbox',{name:'Поиск в журнале'}).fill('');
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Выгрузить CSV',exact:true}).click();const file=await download;
  const csv=readFileSync(await file.path(),'utf8');check(csv.charCodeAt(0)===0xfeff&&csv.includes('Пользователь')&&csv.split('\r\n').length===5,'CSV: BOM, заголовок и четыре записи');
  await page.reload();await page.locator('.node').first().waitFor();await cmd('Журнал действий');
  check(await page.locator('.aud-row').count()===4,'журнал сохраняется после перезагрузки');
  await page.keyboard.press('Escape');
  await page.locator('#projBtn').click();await page.getByText('Другое',{exact:true}).click();await cmd('Журнал действий');
  check(await page.locator('.aud-row').count()===0,'у другого пространства свой журнал');
  await page.keyboard.press('Escape');await page.locator('#projBtn').click();await page.getByText('Аудит',{exact:true}).click();await cmd('Журнал действий');
  await page.getByRole('button',{name:'Очистить журнал',exact:true}).click();
  check((await records()).length===4,'до подтверждения записи не удаляются');
  await page.getByRole('button',{name:'Очистить',exact:true}).click();await page.waitForTimeout(250);
  check((await records()).length===0 && await page.locator('.aud-row').count()===0,'очистка подтверждённого пространства');
  await page.keyboard.press('Escape');await page.locator('.node[data-id="a"]').click();await cmd('Журнал действий');
  const position=await page.locator('.node[data-id="a"]').getAttribute('style');
  await page.getByRole('combobox',{name:'Тип действия'}).focus();await page.keyboard.press('ArrowDown');
  await page.getByRole('button',{name:'Выгрузить CSV',exact:true}).focus();await page.keyboard.press('Delete');
  check(await page.locator('.node[data-id="a"]').count()===1 && await page.locator('.node[data-id="a"]').getAttribute('style')===position,'стрелки и Delete в журнале не меняют выделенный блок');
  await page.keyboard.press('Escape');const peer=await ctx.newPage();await peer.goto('http://127.0.0.1:'+srv.address().port);await peer.locator('.node').first().waitFor();
  await cmd('Новый блок C++');await page.waitForTimeout(900);await peer.waitForTimeout(600);
  check((await records()).length===1 && await peer.locator('.node').count()===2,'обновление во второй вкладке не дублирует запись аудита');
  await peer.close();
  check(errors.length===0,'нет ошибок JavaScript: '+errors.join('; '));await ctx.close();
} finally {await browser.close();await new Promise(ok=>srv.close(ok));}
console.log(failed?'Ошибок: '+failed:'Всё прошло');process.exitCode=failed?1:0;
