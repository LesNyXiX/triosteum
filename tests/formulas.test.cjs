let failed = 0, n = 0;
function cell(formula, data) {
  const rows = (data || [['']]).map((r) => r.slice());
  rows.push([formula]);
  const v = api.computeSheet(rows);
  return v[v.length - 1][0];
}
function eq(formula, want, data) {
  n++;
  const got = cell(formula, data);
  const ok = typeof want === 'number' ? typeof got === 'number' && Math.abs(got - want) < 1e-6 * Math.max(1, Math.abs(want)) : got === want;
  if (!ok) { failed++; console.log('  ✗ ' + formula + ' → ' + JSON.stringify(got) + ', ждали ' + JSON.stringify(want)); }
}
